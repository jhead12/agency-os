    def load_current_user(self, user_id: int) -> Optional[CurrentUser]:
        """Load an active user with roles and effective permissions.

        Called on every request, so role/permission changes and deactivation
        take effect on the user's very next request.
        """
        c = self.conn
        row = c.execute(
            "SELECT id, email, name, is_agent FROM users WHERE id = ? AND is_active = 1", (user_id,)
        ).fetchone()
        if not row:
            return None
        roles = c.execute(
            """SELECT r.name FROM roles r JOIN user_roles ur ON ur.role_id = r.id
               WHERE ur.user_id = ? ORDER BY r.name""",
            (user_id,),
        ).fetchall()
        perms = c.execute(
            """SELECT DISTINCT rp.permission FROM role_permissions rp
               JOIN user_roles ur ON ur.role_id = rp.role_id WHERE ur.user_id = ?""",
            (user_id,),
        ).fetchall()
        prefs = c.execute("SELECT ai_enabled FROM user_prefs WHERE user_id = ?", (user_id,)).fetchone()
        members = c.execute(
            """SELECT campaign, (user_id = ? OR role_id IN (SELECT role_id FROM user_roles WHERE user_id = ?))
                      AS mine
               FROM campaign_members""", (user_id, user_id)).fetchall()
        owned = c.execute("SELECT campaign, user_id = ? AS mine FROM campaign_owners", (user_id,)).fetchall()
        return CurrentUser(
            id=row["id"], email=row["email"], name=row["name"],
            roles=tuple(r["name"] for r in roles),
            permissions=frozenset(p["permission"] for p in perms),
            ai_enabled=bool(prefs and prefs["ai_enabled"]),
            restricted_campaigns=frozenset(m["campaign"] for m in members),
            member_campaigns=frozenset(m["campaign"] for m in members if m["mine"]),
            owner_restricted_campaigns=frozenset(o["campaign"] for o in owned),
            owner_campaigns=frozenset(o["campaign"] for o in owned if o["mine"]),
            is_agent=bool(row["is_agent"]),
        )

