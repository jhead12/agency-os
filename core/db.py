    def apply_enrichment(self, outreach_id: int, result: EnrichmentResult, prospect_id: int = None) -> None:
        c = self.conn
        updates = {}
        if result.contact_name:
            updates["contact_name"] = result.contact_name
        if result.contact_email:
            updates["contact_email"] = result.contact_email
        if result.contact_phone:
            updates["contact_phone"] = result.contact_phone
        if result.contact_title:
            updates["contact_title"] = result.contact_title
        if updates:
            self.update_outreach(outreach_id, updates)
            if result.source:
                # Remember who supplied each field, so the seller can leave out what we may not resell
                c.execute(
                    "UPDATE outreach SET contact_sources = (COALESCE(contact_sources, '{}')::jsonb || ?::jsonb)::text "
                    "WHERE id = ?",
                    (json.dumps({field: result.source for field in updates}), outreach_id),
                )

        # If the enricher discovered a website, save it back to the prospect
        if prospect_id and result.raw.get("website"):
            existing = c.execute(
                "SELECT website_url FROM prospects WHERE id = ?", (prospect_id,)
            ).fetchone()
            if existing and not existing["website_url"]:
                c.execute(
                    "UPDATE prospects SET website_url = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?",
                    (result.raw["website"], prospect_id),
                )

        # Newer is better: the site may have changed since the last scrape
        if prospect_id and result.raw.get("site_summary"):
            c.execute(
                "UPDATE prospects SET site_summary = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?",
                (result.raw["site_summary"], prospect_id),
            )

    def get_upcoming_events(self, days: int = 90, hidden_campaigns=()) -> list[dict]:
        """Get all upcoming follow-ups and call next-steps as calendar events."""
        c = self.conn
        hidden, hidden_params = self.hidden_clause(hidden_campaigns)
        cutoff = (datetime.now() + timedelta(days=days)).isoformat()
        now = datetime.now().isoformat()

        events = []

        # 1. Email follow-ups (next_follow_up_at from outreach)
        rows = c.execute(
            """SELECT o.id, o.next_follow_up_at, o.stage, o.touch_count,
                      o.contact_name, p.id as prospect_id, p.name as prospect_name,
                      p.city, p.state, c.name as campaign_name
               FROM outreach o
               JOIN prospects p ON o.prospect_id = p.id
               JOIN campaigns c ON o.campaign_id = c.id
               WHERE o.next_follow_up_at IS NOT NULL
                 AND o.next_follow_up_at > ?
                 AND o.next_follow_up_at < ?
                 AND o.stage NOT IN ('closed_won', 'closed_lost', 'nurture')
                 AND {hidden}
               ORDER BY o.next_follow_up_at ASC""".format(hidden=hidden),
            (now, cutoff, *hidden_params),
        ).fetchall()

        for r in rows:
            try:
                start = datetime.fromisoformat(r["next_follow_up_at"])
            except (ValueError, TypeError):
                continue

            touch_label = f" (touch {r['touch_count']})" if r["touch_count"] else ""
            events.append({
                "uid": f"followup-{r['id']}",
                "title": f"📧 Follow-up: {r['prospect_name']}{touch_label}",
                "description": (
                    f"Prospect: {r['prospect_name']}\n"
                    f"Stage: {r['stage']}\n"
                    f"Touch #: {r['touch_count']}\n"
                    f"Contact: {r['contact_name'] or 'N/A'}\n"
                    f"Campaign: {r['campaign_name']}\n"
                    f"Link: http://localhost:8000/prospects/{r['prospect_id']}"
                ),
                "start": start,
                "end": start + timedelta(minutes=15),
                "location": f"{r['city'] or ''}, {r['state'] or ''}".strip(", "),
                "type": "followup",
                "prospect_id": r["prospect_id"],
                "prospect_name": r["prospect_name"],
                "date": start,
            })

        # 2. Call next-step dates from call_log
        call_rows = c.execute(
            """SELECT cl.id, cl.next_step_date, cl.next_step, cl.outcome,
                      cl.interest_level, cl.script_title, cl.called_by,
                      p.id as prospect_id, p.name as prospect_name,
                      p.city, p.state
               FROM call_log cl
               JOIN prospects p ON cl.prospect_id = p.id
               WHERE cl.next_step_date IS NOT NULL
                 AND cl.next_step_date > ?
                 AND cl.next_step_date < ?
                 AND {hidden}
               ORDER BY cl.next_step_date ASC""".format(hidden=hidden),
            (now, cutoff, *hidden_params),
        ).fetchall()

        for r in call_rows:
            try:
                start = datetime.fromisoformat(r["next_step_date"])
            except (ValueError, TypeError):
                continue

            events.append({
                "uid": f"call-{r['id']}",
                "title": f"📞 {r['next_step'] or 'Call follow-up'}: {r['prospect_name']}",
                "description": (
                    f"Prospect: {r['prospect_name']}\n"
                    f"Next step: {r['next_step']}\n"
                    f"Previous call outcome: {r['outcome']}\n"
                    f"Interest: {r['interest_level'] or 'N/A'}\n"
                    f"Script used: {r['script_title'] or 'N/A'}\n"
                    f"Called by: {r['called_by'] or 'N/A'}\n"
                    f"Link: http://localhost:8000/prospects/{r['prospect_id']}"
                ),
                "start": start,
                "end": start + timedelta(minutes=30),
                "location": f"{r['city'] or ''}, {r['state'] or ''}".strip(", "),
                "type": "call",
                "prospect_id": r["prospect_id"],
                "prospect_name": r["prospect_name"],
                "date": start,
            })

        # Sort all events by date
        events.sort(key=lambda e: e["date"])
        return events

    def get_upcoming_events_for_prospect(self, prospect_id: int, days: int = 90) -> list[dict]:
        """Get upcoming events for a specific prospect."""
        all_events = self.get_upcoming_events(days)
