    def get_all_calls(self, limit: int = 100, offset: int = 0,
                      outcome: str = "", interest: str = "", hidden_campaigns=()) -> list:
        """Get all call logs, newest first, with optional filters."""
        where_parts = []
        params = []
        if hidden_campaigns:
            clause, hidden_params = self.hidden_clause(hidden_campaigns, "cl.prospect_id")
            where_parts.append(clause)
            params.extend(hidden_params)
        if outcome:
            where_parts.append("cl.outcome = ?")
            params.append(outcome)
        if interest:
            where_parts.append("cl.interest_level = ?")
            params.append(interest)
        where_clause = " AND ".join(where_parts) if where_parts else "1=1"

        rows = self.conn.execute(
            f"""SELECT cl.*, p.name as prospect_name, p.city as prospect_city,
               c.name as campaign_name
               FROM call_log cl
               JOIN prospects p ON cl.prospect_id = p.id
               JOIN campaigns c ON cl.campaign_id = c.id
               WHERE {where_clause}
               ORDER BY cl.called_at DESC
               LIMIT ? OFFSET ?""",
            params + [limit, offset],
        ).fetchall()
        return rows

    def get_call_stats(self, campaign_name: str = "", hidden_campaigns=()) -> dict:
        """Aggregate call statistics."""
        c = self.conn
        hidden, params = self.hidden_clause(hidden_campaigns, "cl.prospect_id")
        where = f"WHERE {hidden}"
        if campaign_name:
            where += " AND c.name = ?"
            params = params + [campaign_name]

        total = c.execute(
            f"""SELECT COUNT(*) FROM call_log cl
               JOIN campaigns c ON cl.campaign_id = c.id {where}""",
            params,
        ).fetchone()[0]

        by_outcome = {}
        rows = c.execute(
            f"""SELECT cl.outcome, COUNT(*) as cnt FROM call_log cl
               JOIN campaigns c ON cl.campaign_id = c.id {where}
               GROUP BY cl.outcome""",
            params,
        ).fetchall()
        for r in rows:
            by_outcome[r["outcome"]] = r["cnt"]

        by_interest = {}
        rows = c.execute(
            f"""SELECT cl.interest_level, COUNT(*) as cnt FROM call_log cl
               JOIN campaigns c ON cl.campaign_id = c.id {where}
               AND cl.interest_level IS NOT NULL
               GROUP BY cl.interest_level""",
            params,
        ).fetchall()
        for r in rows:
            by_interest[r["interest_level"]] = r["cnt"]

        total_minutes = c.execute(
            f"""SELECT COALESCE(SUM(cl.duration_minutes), 0) FROM call_log cl
               JOIN campaigns c ON cl.campaign_id = c.id {where}""",
            params,
        ).fetchone()[0]

        return {
            "total_calls": total,
            "by_outcome": by_outcome,
            "by_interest": by_interest,
            "total_minutes": total_minutes,
        }

    # ── Users, roles & sessions ────────────────────────────────────────
    # Policy (catalog, route rules, password hashing) lives in core/access.py.

    @contextmanager
    def transaction(self) -> Iterator[Connection]:
        """Write transaction that takes a global write lock up front, so
        invariant checks like "at least one active owner" can't race."""
        c = self.conn
        c.execute("SELECT 1")  # reconnects first if the server dropped the idle connection
        with c.raw.transaction():
            c.execute("SELECT pg_advisory_xact_lock(?)", (_WRITE_LOCK_ID,))
            yield c

    def install_access(self) -> None:
        """Create the protected Owner and Super Admin roles and any missing starter roles.

        Idempotent. Never touches a role that already exists, so owner edits
        to starter roles survive restarts.
        """
        with self.transaction() as c:
            c.execute(
                """INSERT INTO roles (name, description, is_protected) VALUES (?, ?, 1)
                   ON CONFLICT DO NOTHING""",
                (access.OWNER_ROLE, "Full access, including managing users and roles"),
            )
            c.execute(
                """INSERT INTO roles (name, description, is_protected) VALUES (?, ?, 1)
                   ON CONFLICT DO NOTHING""",
                (access.SUPER_ADMIN_ROLE, "Everything an Owner can do, plus creating and promoting Owners"),
            )
            for name, (description, permissions) in access.STARTER_ROLES.items():
                created = c.execute(
                    """INSERT INTO roles (name, description) VALUES (?, ?)
                       ON CONFLICT DO NOTHING RETURNING id""",
                    (name, description),
                ).fetchone()
                if created:
                    c.executemany(
                        "INSERT INTO role_permissions (role_id, permission) VALUES (?, ?)",
                        [(created["id"], p) for p in permissions],
                    )

