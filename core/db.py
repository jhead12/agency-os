    def campaign_spend(self, campaign_id: int) -> dict:
        """Settled spend by kind, this month's committed spend, and pending count."""
        c = self.conn
        rows = c.execute(
            """SELECT kind, COUNT(*) AS n, COALESCE(SUM(amount_atomic), 0) AS total FROM spend
               WHERE campaign_id = ? AND status = 'settled' GROUP BY kind""",
            (campaign_id,),
        ).fetchall()
        month = c.execute(
            """SELECT COALESCE(SUM(amount_atomic), 0) AS total FROM spend
               WHERE campaign_id = ? AND status IN ('pending', 'settled') AND kind IN ('unlock', 'royalty')
                 AND created_at >= date_trunc('month', CURRENT_TIMESTAMP)""",
            (campaign_id,),
        ).fetchone()["total"]
        pending = c.execute(
            "SELECT COUNT(*) AS n FROM spend WHERE campaign_id = ? AND status = 'pending'",
            (campaign_id,),
        ).fetchone()["n"]
        by_kind = {r["kind"]: {"count": r["n"], "total_atomic": r["total"]} for r in rows}
        refunds = by_kind.get("refund_in", {}).get("total_atomic", 0)
        return {
            "by_kind": by_kind,
            # Net of refunds received from guarantee claims.
            "total_atomic": sum(v["total_atomic"] for k, v in by_kind.items() if k != "refund_in") - refunds,
            "refunds_atomic": refunds,
            "month_atomic": month,
            "pending": pending,
        }

