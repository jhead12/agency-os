    def resolve_spend(self, spend_id: int, status: str, tx_hash: str, actor: Optional[CurrentUser]) -> bool:
        """Settle or fail a pending payment after checking it onchain. False if not pending.

        Marking it failed releases its budget and lets the payment be retried.
        """
        if status not in ("settled", "failed"):
            raise ValueError("status must be settled or failed")
        if status == "settled" and not re.fullmatch(r"0x[0-9a-fA-F]{64}", tx_hash or ""):
            raise ValueError("A settled payment needs its 0x transaction hash")
        with self.transaction() as c:
            row = c.execute(
                """UPDATE spend SET status = ?, tx_hash = COALESCE(?, tx_hash),
                       error = CASE WHEN ? = 'failed' THEN 'Resolved as failed' ELSE NULL END,
                       updated_at = CURRENT_TIMESTAMP
                   WHERE id = ? AND status = 'pending' RETURNING id""",
                (status, tx_hash or None, status, spend_id),
            ).fetchone()
            if row is None:
                return False
            self._audit(c, actor, "spend.resolve", "spend", spend_id, {"status": status, "tx_hash": tx_hash})
        return True

